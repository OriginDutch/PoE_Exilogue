'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('ej', {
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: patch => ipcRenderer.invoke('config:set', patch),
  snapshot: () => ipcRenderer.invoke('snapshot'),
  events: q => ipcRenderer.invoke('events:get', q),
  allMaps: () => ipcRenderer.invoke('maps:all'),
  launch: which => ipcRenderer.invoke('launch', which),
  wealthSync: () => ipcRenderer.invoke('wealth:sync'),
  goalSearch: q => ipcRenderer.invoke('goal:search', q),
  sheetSearch: q => ipcRenderer.invoke('sheet:search', q),
  weOpen: () => ipcRenderer.invoke('we:open'),
  weTest: () => ipcRenderer.invoke('we:test'),
  weLogout: () => ipcRenderer.invoke('we:logout'),
  sheetOpen: () => ipcRenderer.invoke('sheet:open'),
  sheetPin: on => ipcRenderer.invoke('sheet:pin', on),
  sheetSort: (id, sort) => ipcRenderer.invoke('sheet:sort', id, sort),
  sheetRefresh: () => ipcRenderer.invoke('sheet:refresh'),
  openUrl: url => ipcRenderer.invoke('open:url', url),
  pickFile: opts => ipcRenderer.invoke('pick:file', opts),
  neversinkSynced: () => ipcRenderer.invoke('neversink:synced'),
  resetLeague: () => ipcRenderer.invoke('league:reset'),
  checkProfile: () => ipcRenderer.invoke('profile:check'),
  listBackups: () => ipcRenderer.invoke('backups:list'),
  storage: () => ipcRenderer.invoke('storage:get'),
  breakTaken: () => ipcRenderer.invoke('break:taken'),
  updateInstall: () => ipcRenderer.invoke('update:install'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  icons: () => ipcRenderer.invoke('icons:get'),
  setVisible: v => ipcRenderer.send('win:visible', v),
  restoreBackup: file => ipcRenderer.invoke('backups:restore', file),
  pauseHotkeys: p => ipcRenderer.invoke('hotkeys:pause', p),
  lockOverlay: locked => ipcRenderer.invoke('overlay:lock', locked),
  resetOverlay: () => ipcRenderer.invoke('overlay:reset'),
  overlayBounds: () => ipcRenderer.invoke('overlay:bounds'),
  fitOverlay: (h, extra, side) => ipcRenderer.send('overlay:fit', h, extra, side),
  setOverlayBounds: b => ipcRenderer.send('overlay:setBounds', b),
  overlayBoundsDone: () => ipcRenderer.send('overlay:boundsDone'),
  win: {
    min: () => ipcRenderer.send('win:min'),
    max: () => ipcRenderer.send('win:max'),
    close: () => ipcRenderer.send('win:close'),
    state: () => ipcRenderer.invoke('win:state'),
    onState: fn => ipcRenderer.on('win:state', (_e, s) => fn(s)),
  },
  onSnapshot: fn => ipcRenderer.on('snapshot', (_e, s) => fn(s)),
  onTick: fn => ipcRenderer.on('tick', (_e, t) => fn(t)),
  onConfig: fn => ipcRenderer.on('config', (_e, c) => fn(c)),
  onOverlayUnlocked: fn => ipcRenderer.on('overlay:unlocked', (_e, u) => fn(u)),
});
